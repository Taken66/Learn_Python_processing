# 列表推导式
# 题目：用一行代码完成下列任务：
#  ① 生成 1–20 的平方列表
#  ② 从 1–20 中筛出所有偶数
#  ③ 把 \["a", "b", "c"] 变成 \["a1", "b1", "c1"]
#  ④ 从 \[1, -2, 3, -4, 5] 中筛出正数并平方

# 验收标准：

# [ ] 全部用推导式，不许用 for 循环
# [ ] ④ 中既筛又算，写在一条推导式里
# [ ] 能说出推导式里 if 放在前和放在后的区别

y = [x**2 for x in range(1,21)]
print(f" 1–20 的平方列表: {y}")
y = [i for i in range(1,21) if i%2==0 ]
print(f" 1–20 的偶数列表: {y}")

x = ["a", "b", "c"]
y = [ i + "1" for i in x]
print("变形:",y)

x = [1, -2, 3, -4, 5]
y=[i**2 for i in x if i>0]
print("筛出正数并平方:",y)
